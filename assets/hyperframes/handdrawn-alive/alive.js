/*
 * handdrawn-alive — keeps a hand-drawn HyperFrames scene moving while it "holds".
 *
 * What the reference videos actually do while a shot holds (measured by
 * scripts/style_refs/motion_analysis.py, see the reference motion folder):
 *   - the main drawing stays still: no line boil, and the paper texture is fixed
 *   - small secondary props keep happening around it, roughly one every
 *     0.6-1.5 s: icons pop in one after another, bubbles rise out of a head,
 *     pieces of a pattern dissolve away one by one, blocks slide
 *   - everything animated moves "on twos": the picture updates 12 times a second
 *   - about 4 shots in 10 carry a slow camera push-in or pan
 *
 * Every number comes from motion-profile.json via profile.js (generated by
 * scripts/style_refs/build_alive_profile.py); DEFAULTS are fallbacks only.
 *
 * Markup (inside any timed .clip):
 *   <div class="alive-hold">                 camera drift on the whole shot
 *     <div class="alive-pop"><i>..</i><i>..</i></div>      children pop in, staggered
 *     <div class="alive-float" data-count="6">..</div>     children rise and fade, staggered
 *     <div class="alive-scatter"><i>..</i>..</div>         children shrink away, staggered
 *     <g class="alive-blink">..</g>  <g class="alive-breathe">..</g>  <g class="alive-sway">..</g>
 *     <div class="alive-boil">..</div>       optional line wobble (off unless measured)
 *   </div>
 *   <div class="alive-grain"></div>          fixed paper texture, once per composition
 *
 *   const tl = gsap.timeline({ paused: true });
 *   HandDrawnAlive.apply(tl, document.getElementById("root"));
 *   window.__timelines["main"] = tl;
 *
 * Determinism: no clocks, seeded PRNG, finite repeats, stepped eases are pure
 * functions of progress, so any seek renders the same frame.
 */
(function () {
  "use strict";

  var DEFAULTS = {
    stepFps: 12,               // animated elements update on twos at 24 fps
    boilCadenceSeconds: 0,     // 0 = no line boil (references hold lines still)
    boilAmplitudePx: 0,
    grainOpacity: 0.12,        // fixed paper texture, never flickers
    driftPanPxPerS: 20,
    driftZoomPctPerS: 0.8,
    driftEase: "sine.in",
    shareOfShotsMoving: 0.42,
    secondaryEventGapSeconds: 0.65, // one secondary prop event this often while holding
    popSeconds: 0.25,
    floatSeconds: 1.6,
    floatRisePx: 90,
    scatterSeconds: 0.3,
    idleBlinkGapSeconds: 3.5,
    seed: 7,
  };

  function mulberry32(a) {
    return function () {
      a |= 0; a = (a + 0x6d2b79f5) | 0;
      var t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  function readProfile() {
    var p = (typeof window !== "undefined" && window.HANDDRAWN_ALIVE_PROFILE) || {};
    var o = {};
    for (var k in DEFAULTS) o[k] = p[k] != null ? p[k] : DEFAULTS[k];
    return o;
  }

  // Quantise any ease so the value only changes stepFps times a second of the
  // tween, which is what makes digital motion read as drawn animation.
  function onTwos(easeName, duration, stepFps) {
    var base = gsap.parseEase(easeName || "none");
    var n = Math.max(1, Math.round(duration * stepFps));
    return function (p) { return p >= 1 ? 1 : base(Math.floor(p * n) / n); };
  }

  var SVG_NS = "http://www.w3.org/2000/svg";

  function injectDefs(root, cfg) {
    if (root.querySelector(".alive-defs")) return;
    var svg = document.createElementNS(SVG_NS, "svg");
    svg.setAttribute("class", "alive-defs");
    svg.setAttribute("width", "0");
    svg.setAttribute("height", "0");
    svg.style.position = "absolute";
    svg.innerHTML =
      '<defs>' +
      '<filter id="alive-boil-filter" x="-2%" y="-2%" width="104%" height="104%">' +
      '<feTurbulence id="alive-boil-noise" type="fractalNoise" baseFrequency="0.018" numOctaves="2" seed="0" result="n"/>' +
      '<feDisplacementMap in="SourceGraphic" in2="n" scale="' + (cfg.boilAmplitudePx * 2).toFixed(2) +
      '" xChannelSelector="R" yChannelSelector="G"/>' +
      '</filter>' +
      // paper: soft blotches plus fine tooth, fixed seed so it never flickers
      '<filter id="alive-paper-filter" x="0" y="0" width="100%" height="100%">' +
      '<feTurbulence type="fractalNoise" baseFrequency="0.006" numOctaves="3" seed="11" result="blot"/>' +
      '<feTurbulence type="fractalNoise" baseFrequency="0.85" numOctaves="2" seed="5" result="tooth"/>' +
      '<feBlend in="blot" in2="tooth" mode="multiply" result="mix"/>' +
      '<feColorMatrix in="mix" type="matrix" values="0 0 0 0 0.42  0 0 0 0 0.38  0 0 0 0 0.36  -1.2 0 0 0 1.1"/>' +
      '</filter>' +
      '</defs>';
    root.insertBefore(svg, root.firstChild);
    var style = document.createElement("style");
    style.textContent =
      (cfg.boilAmplitudePx > 0 ? ".alive-boil{filter:url(#alive-boil-filter)}" : "") +
      ".alive-grain{position:absolute;inset:0;pointer-events:none;z-index:50;mix-blend-mode:multiply;opacity:" +
      cfg.grainOpacity + "}" +
      ".alive-grain svg{width:100%;height:100%;display:block}" +
      ".alive-hold{transform-origin:50% 55%}" +
      ".alive-pop>*,.alive-float>*,.alive-scatter>*{display:block;transform-origin:50% 50%}";
    root.appendChild(style);
    root.querySelectorAll(".alive-grain").forEach(function (g) {
      if (!g.querySelector("svg")) {
        g.innerHTML = '<svg preserveAspectRatio="none"><rect width="100%" height="100%" filter="url(#alive-paper-filter)"/></svg>';
      }
    });
  }

  function clipWindow(el, root) {
    var clip = el.closest(".clip") || el.closest("[data-start]") || root;
    return {
      start: parseFloat(clip.getAttribute("data-start")) || 0,
      dur: parseFloat(clip.getAttribute("data-duration")) || parseFloat(root.getAttribute("data-duration")) || 0,
    };
  }

  function applyBoil(tl, root, cfg, duration) {
    var noise = root.querySelector("#alive-boil-noise");
    if (!noise || !(cfg.boilCadenceSeconds > 0) || !(cfg.boilAmplitudePx > 0)) return;
    var steps = Math.max(1, Math.floor(duration / cfg.boilCadenceSeconds));
    tl.fromTo(noise, { attr: { seed: 1 } },
      { attr: { seed: 1 + steps }, duration: steps * cfg.boilCadenceSeconds, ease: "steps(" + steps + ")" }, 0);
  }

  function applyDrift(tl, root, cfg, rand) {
    root.querySelectorAll(".alive-hold").forEach(function (el) {
      var w = clipWindow(el, root);
      var forced = el.getAttribute("data-drift"); // "on" | "off" overrides the dice
      if (w.dur <= 0 || forced === "off" || (forced !== "on" && rand() > cfg.shareOfShotsMoving)) return;
      var zoom = 1 + (cfg.driftZoomPctPerS / 100) * w.dur;
      var angle = rand() * Math.PI * 2;
      var dist = cfg.driftPanPxPerS * w.dur;
      tl.fromTo(el, { scale: 1, x: 0, y: 0 },
        { scale: zoom, x: Math.cos(angle) * dist, y: Math.sin(angle) * dist * 0.4,
          duration: w.dur, ease: cfg.driftEase }, w.start);
    });
  }

  // Secondary props share one clock per shot so they never bunch up:
  // each event is scheduled one "gap" after the previous, with jitter.
  function eventTimes(w, count, cfg, rand, lead) {
    var times = [], t = w.start + (lead != null ? lead : 0.3);
    for (var i = 0; i < count && t < w.start + w.dur - 0.2; i++) {
      times.push(t);
      t += cfg.secondaryEventGapSeconds * (0.6 + rand() * 0.8);
    }
    return times;
  }

  function applyPop(tl, root, cfg, rand) {
    root.querySelectorAll(".alive-pop").forEach(function (group) {
      var w = clipWindow(group, root);
      var kids = Array.prototype.slice.call(group.children);
      var lead = parseFloat(group.getAttribute("data-lead")) || 0.3;
      eventTimes(w, kids.length, cfg, rand, lead).forEach(function (t, i) {
        var d = cfg.popSeconds;
        tl.fromTo(kids[i], { scale: 0, opacity: 0 },
          { scale: 1, opacity: 1, duration: d, ease: onTwos("back.out(2.2)", d, cfg.stepFps) }, t);
      });
    });
  }

  function applyFloat(tl, root, cfg, rand) {
    root.querySelectorAll(".alive-float").forEach(function (group) {
      var w = clipWindow(group, root);
      var kids = Array.prototype.slice.call(group.children);
      var rise = parseFloat(group.getAttribute("data-rise")) || cfg.floatRisePx;
      var lead = parseFloat(group.getAttribute("data-lead")) || 0.2;
      eventTimes(w, kids.length, cfg, rand, lead).forEach(function (t, i) {
        var d = Math.min(cfg.floatSeconds, w.start + w.dur - t);
        var dx = (rand() - 0.5) * rise * 0.6;
        var ease = onTwos("sine.out", d, cfg.stepFps);
        tl.fromTo(kids[i], { x: 0, y: 0, scale: 0.3, opacity: 0 },
          { x: dx, y: -rise, scale: 1, opacity: 1, duration: d * 0.45, ease: ease }, t);
        tl.to(kids[i], { y: -rise * 1.6, opacity: 0, duration: d * 0.55, ease: onTwos("sine.in", d * 0.55, cfg.stepFps) }, t + d * 0.45);
      });
    });
  }

  function applyScatter(tl, root, cfg, rand) {
    root.querySelectorAll(".alive-scatter").forEach(function (group) {
      var w = clipWindow(group, root);
      var kids = Array.prototype.slice.call(group.children);
      // shuffle deterministically so pieces leave in a scattered order
      for (var i = kids.length - 1; i > 0; i--) {
        var j = Math.floor(rand() * (i + 1)); var tmp = kids[i]; kids[i] = kids[j]; kids[j] = tmp;
      }
      var start = w.start + (parseFloat(group.getAttribute("data-lead")) || w.dur * 0.35);
      var span = Math.max(0.5, w.start + w.dur - 0.3 - start);
      kids.forEach(function (k, i) {
        var t = start + (span * i) / kids.length;
        var d = cfg.scatterSeconds;
        tl.to(k, { scale: 0, opacity: 0, duration: d, ease: onTwos("power2.in", d, cfg.stepFps) }, t);
      });
    });
  }

  function applyIdle(tl, root, cfg, rand) {
    root.querySelectorAll(".alive-blink").forEach(function (el) {
      var w = clipWindow(el, root);
      var gap = cfg.idleBlinkGapSeconds;
      var t = w.start + 0.8 + rand() * gap * 0.5;
      while (t < w.start + w.dur - 0.3) {
        // two drawings: closed for 2 frames, then open (on twos)
        tl.set(el, { scaleY: 0.1, transformOrigin: "50% 50%" }, t);
        tl.set(el, { scaleY: 1 }, t + 2 / 24);
        t += gap * (0.6 + rand() * 0.8);
      }
    });
    root.querySelectorAll(".alive-breathe").forEach(function (el) {
      var w = clipWindow(el, root);
      var cycle = 3.2 + rand() * 0.8;
      var reps = Math.max(0, Math.floor(w.dur / (cycle / 2)) - 1);
      tl.fromTo(el, { scaleY: 1, transformOrigin: "50% 100%" },
        { scaleY: 1.012, duration: cycle / 2, ease: onTwos("sine.inOut", cycle / 2, cfg.stepFps), yoyo: true, repeat: reps }, w.start);
    });
    root.querySelectorAll(".alive-sway").forEach(function (el) {
      var w = clipWindow(el, root);
      var cycle = 4 + rand() * 1.5;
      var reps = Math.max(0, Math.floor(w.dur / (cycle / 2)) - 1);
      tl.fromTo(el, { rotation: -0.8, transformOrigin: "50% 90%" },
        { rotation: 0.8, duration: cycle / 2, ease: onTwos("sine.inOut", cycle / 2, cfg.stepFps), yoyo: true, repeat: reps }, w.start);
    });
  }

  function apply(tl, root, opts) {
    opts = opts || {};
    var cfg = readProfile();
    for (var k in opts) if (k in cfg) cfg[k] = opts[k];
    var duration = opts.duration || parseFloat(root.getAttribute("data-duration")) || tl.duration();
    var rand = mulberry32(cfg.seed);
    injectDefs(root, cfg);
    applyBoil(tl, root, cfg, duration);
    applyDrift(tl, root, cfg, rand);
    applyPop(tl, root, cfg, rand);
    applyFloat(tl, root, cfg, rand);
    applyScatter(tl, root, cfg, rand);
    applyIdle(tl, root, cfg, rand);
    return cfg;
  }

  window.HandDrawnAlive = { apply: apply, onTwos: onTwos, defaults: DEFAULTS };
})();
